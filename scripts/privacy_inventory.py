#!/usr/bin/env python3
"""Per-tool data table on the privacy page, generated from the public surface contract.

The privacy policy must reflect the current tool inputs (OpenAI rejected 0.1.6 on exactly this). The table between the
markers in ``site/privacy.html`` is a generated mirror of ``public_surface.json``: run with ``--write`` after changing the
contract, and ``verify_site.py`` refuses to publish when the page and the contract disagree.

A field that is not classified below stops the generator. Decide what kind of personal data a new field is (free text?
someone else's data? a place?) and say so on the page before adding it here.
"""
from __future__ import annotations

import html
import json
import sys
from pathlib import Path

PROJECT = Path(__file__).resolve().parents[1]
CONTRACT = PROJECT / "src/horosa_public/contracts/public_surface.json"
PAGE = PROJECT / "site/privacy.html"
START, END = "<!-- inventory:start (generated by scripts/privacy_inventory.py; do not edit by hand) -->", "<!-- inventory:end -->"

# Every contract field, by the kind of data it is. Order here is the order on the page.
CATEGORIES: list[tuple[str, str, str, frozenset[str]]] = [
    ("when", "日期、时间、时区", "date, time, timezone", frozenset({"date", "time", "zone", "ad", "year", "hour"})),
    ("place", "地点坐标", "place coordinates", frozenset({"lat", "lon"})),
    ("second", "两个人各自的出生日期、时间、时区和出生地", "two people's birth date, time, timezone and birthplace", frozenset({"inner", "outer"})),
    ("target", "目标日期、时刻或时段", "target date, time or range",
     frozenset({"datetime", "targetDate", "targetTime", "transitDate", "tajakaYear", "moiraTransitDate", "moiraTransitTime",
                "startDate", "endDate"})),
    ("target_place", "可选的目标地点（城市级）与其时区", "optional target place (city level) and its timezone",
     frozenset({"dirZone", "dirLat", "dirLon"})),
    ("gender", "命盘性别设置", "chart gender setting", frozenset({"gender"})),
    ("text", "问题文字（自由文本，可选）", "question text (free text, optional)", frozenset({"question", "questionText", "askEvent"})),
    ("values", "你给出的数字、卦码、爻或随机种子", "numbers, hexagram codes, lines or a random seed you give",
     frozenset({"seed", "nums", "gua_code", "changed_code", "lines"})),
    ("settings", "计算设置", "calculation settings",
     frozenset({"hsys", "zodiacal", "siderealAyanamsa", "tradition", "southchart", "cnUnifiedZone", "relative", "indiaHsys",
                "indiaAyanamsa", "indiaSchool", "dashaSystem", "dashaYearLength", "doubingSu28", "guolaoTrueSolarTime",
                "category", "school", "considerationsMode", "lotsSet", "sincerityConfirmed", "topicId", "tradeSide",
                "profGrain", "profStart", "minorVariant", "includeTransits", "eclipseTimeMode", "timeAlg", "after23NewDay",
                "lateZiHourUseNextDay", "southMonth", "cangVersion", "fenyeVersion", "zodiacBoundary", "period", "sihuaSchool",
                "options", "yue", "isDiurnal", "guirengType", "liuyaoSettings", "showOneThree", "spread", "deck",
                "usesReversals", "dignities", "variant", "verdictMode"})),
]
# Sent with every tool; described once above the table instead of on every row.
GATE = frozenset({"agent_confirmed_settings", "defaults_accepted", "clarification_notes"})

PLACE = {
    "user": ("必填：出生地或事件地点，城市级", "Required: birthplace or event place, city level"),
    "user_optional": ("可选：出生地，只影响真太阳时", "Optional: birthplace, only for true solar time"),
    "client": ("不收地点；用 ChatGPT 的粗略位置（如你共享）", "No place input; ChatGPT's coarse location, if you share it"),
    "none": ("不用地点", "No place"),
}
PLACE_CLIENT_HINT = ("可选：提问地点；未给时用 ChatGPT 的粗略位置（如你共享）",
                     "Optional: place of the question; otherwise ChatGPT's coarse location, if you share it")
PLACE_PARTIES = ("必填：两个人的出生地，城市级", "Required: both birthplaces, city level")


class UnclassifiedField(Exception):
    pass


def _fields(tool: dict, groups: dict[str, list[str]]) -> list[str]:
    names: list[str] = []
    for group in tool["field_groups"]:
        names += groups[group]
    names += tool.get("optional_fields", []) + tool["fields"]
    return list(dict.fromkeys(name for name in names if name not in GATE))


def _cell(zh: str, en: str) -> str:
    return f'{html.escape(zh)}<span lang="en">{html.escape(en)}</span>'


def rows(contract: dict) -> list[tuple[str, str, str, str]]:
    known = set().union(*(members for *_, members in CATEGORIES))
    out: list[tuple[str, str, str, str]] = []
    for tool in contract["tools"]:
        fields = _fields(tool, contract["field_groups"])
        unknown = sorted(set(fields) - known)
        if unknown:
            raise UnclassifiedField(f"{tool['name']}: classify {unknown} in scripts/privacy_inventory.py and describe them on the privacy page")
        if "inner" in fields:
            place = PLACE_PARTIES
        elif tool.get("client_hint"):
            place = PLACE_CLIENT_HINT
        else:
            place = PLACE[tool["place"]]
        parts = []
        for key, zh, en, members in CATEGORIES:
            used = [name for name in fields if name in members]
            if not used or key == "place":
                continue
            label = _cell(zh, en)
            if key in ("settings", "values", "text", "target", "target_place"):
                label += " <code>" + html.escape(", ".join(used)) + "</code>"
            parts.append(label)
        out.append((tool["name"], _tool_cell(tool), _cell(*place), "<br>".join(parts)))
    guidance = contract["guidance"]
    out.append((guidance["name"], _tool_cell(guidance), _cell(*PLACE["none"]),
                _cell("要说明的工具名", "name of the tool to explain") + " <code>tool_name</code>"))
    return out


def _tool_cell(tool: dict) -> str:
    # Contract titles are written "English / 中文"; the site shows 中文 first.
    title_en, title_zh = (part.strip() for part in tool["title"].split("/", 1))
    return f'<code>{html.escape(tool["name"])}</code><br>{_cell(title_zh, title_en)}'


def render(contract: dict) -> str:
    body = "\n".join(f'<tr><th scope="row">{tool}</th><td>{place}</td><td>{inputs}</td></tr>' for _, tool, place, inputs in rows(contract))
    return (f'{START}\n<div class="inventory"><table>\n'
            f'<caption>{_cell(f"{len(contract["tools"]) + 1} 个工具各收哪些输入", f"Inputs each of the {len(contract["tools"]) + 1} tools accepts")}</caption>\n'
            f'<thead><tr><th scope="col">{_cell("工具", "Tool")}</th><th scope="col">{_cell("地点", "Place")}</th>'
            f'<th scope="col">{_cell("其他输入", "Other inputs")}</th></tr></thead>\n<tbody>\n{body}\n</tbody></table></div>\n{END}')


def current(page_text: str) -> str | None:
    start, end = page_text.find(START), page_text.find(END)
    return None if start < 0 or end < 0 else page_text[start:end + len(END)]


def check(page: Path | None = None, contract_path: Path | None = None) -> list[str]:
    page, contract_path = page or PAGE, contract_path or CONTRACT
    contract = json.loads(contract_path.read_text(encoding="utf-8"))
    try:
        expected = render(contract)
    except UnclassifiedField as exc:
        return [f"privacy.html: {exc}"]
    found = current(page.read_text(encoding="utf-8"))
    if found is None:
        return ["privacy.html: per-tool data table markers missing"]
    if found != expected:
        return ["privacy.html: per-tool data table is out of date with public_surface.json; run scripts/privacy_inventory.py --write"]
    return []


def write(page: Path | None = None, contract_path: Path | None = None) -> None:
    page, contract_path = page or PAGE, contract_path or CONTRACT
    text = page.read_text(encoding="utf-8")
    found = current(text)
    if found is None:
        raise SystemExit("privacy.html: add the inventory markers first")
    page.write_text(text.replace(found, render(json.loads(contract_path.read_text(encoding="utf-8")))), encoding="utf-8")


if __name__ == "__main__":
    if "--write" in sys.argv:
        write()
    problems = check()
    for problem in problems:
        print(problem, file=sys.stderr)
    raise SystemExit(2 if problems else 0)
